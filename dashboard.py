from reportlab.platypus import SimpleDocTemplate, Paragraph
from reportlab.lib.styles import getSampleStyleSheet

def generate_report(city, aqi, pm25, pm10, category):

    pdf = SimpleDocTemplate("AQI_Report.pdf")
    styles = getSampleStyleSheet()

    story = []

    story.append(Paragraph("<b>AI Air Quality Prediction Report</b>", styles["Title"]))
    story.append(Paragraph("<br/>", styles["Normal"]))

    story.append(Paragraph(f"<b>City:</b> {city}", styles["BodyText"]))
    story.append(Paragraph(f"<b>AQI:</b> {aqi}", styles["BodyText"]))
    story.append(Paragraph(f"<b>PM2.5:</b> {pm25}", styles["BodyText"]))
    story.append(Paragraph(f"<b>PM10:</b> {pm10}", styles["BodyText"]))
    story.append(Paragraph(f"<b>Category:</b> {category}", styles["BodyText"]))

    story.append(Paragraph("<br/>", styles["Normal"]))
    story.append(Paragraph("Generated by AI Air Quality Prediction Dashboard", styles["Italic"]))

    pdf.build(story)

    return "AQI_Report.pdf"