from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch
from datetime import datetime


def generate_report(city, aqi, pm25, pm10, category):

    file_name = "FINAL_AQI_REPORT.pdf"

    pdf = SimpleDocTemplate(
        file_name,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = styles["Title"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.darkblue

    heading_style = styles["Heading2"]
    heading_style.textColor = colors.darkblue

    normal_style = styles["BodyText"]

    elements = []

    # Title
    elements.append(
        Paragraph("🌍 AI AIR QUALITY REPORT", title_style)
    )

    elements.append(Spacer(1, 0.3 * inch))

    elements.append(
        Paragraph(
            "This report is automatically generated by the AI Air Quality Prediction Dashboard.",
            normal_style,
        )
    )

    elements.append(Spacer(1, 0.25 * inch))

    # AQI Status
    if aqi <= 50:
        status = "GOOD"
        clr = colors.green
    elif aqi <= 100:
        status = "SATISFACTORY"
        clr = colors.orange
    elif aqi <= 200:
        status = "MODERATE"
        clr = colors.darkorange
    elif aqi <= 300:
        status = "POOR"
        clr = colors.red
    else:
        status = "VERY POOR"
        clr = colors.purple

    elements.append(
        Paragraph(
            f"<font color='{clr.hexval()}'><b>Current AQI Status : {status}</b></font>",
            heading_style,
        )
    )

    elements.append(Spacer(1, 0.25 * inch))

    # Table
    data = [
        ["Parameter", "Value"],
        ["City", city],
        ["AQI", str(aqi)],
        ["PM2.5", str(pm25)],
        ["PM10", str(pm10)],
        ["Category", category],
        ["Date", datetime.now().strftime("%d-%m-%Y")],
    ]

    table = Table(data, colWidths=[180, 250])

    table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.darkblue),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("GRID", (0, 0), (-1, -1), 1, colors.grey),
            ("BACKGROUND", (0, 1), (-1, -1), colors.beige),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 10),
            ("TOPPADDING", (0, 1), (-1, -1), 8),
        ])
    )

    elements.append(table)

    elements.append(Spacer(1, 0.5 * inch))

    elements.append(
        Paragraph(
            "<b>Health Recommendation</b>",
            heading_style,
        )
    )

    if aqi <= 100:
        msg = "Air quality is acceptable. Outdoor activities are generally safe."
    elif aqi <= 200:
        msg = "Sensitive people should reduce prolonged outdoor activities."
    else:
        msg = "Wear a mask and avoid prolonged outdoor exposure."

    elements.append(Paragraph(msg, normal_style))

    elements.append(Spacer(1, 0.5 * inch))

    elements.append(
        Paragraph(
            "<font color='grey'>Generated by AI Air Quality Prediction Dashboard | Python • Streamlit • Machine Learning</font>",
            normal_style,
        )
    )

    pdf.build(elements)

    return file_name